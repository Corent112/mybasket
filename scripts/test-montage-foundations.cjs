const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
// Exercise the actual TypeScript services without adding a test dependency.
const previous = require.extensions['.ts'];
require.extensions['.ts'] = (mod, filename) => mod._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
const data = require('../lib/montage/multi-match-data.ts');
const sequence = require('../lib/montage/timeline-sequence.ts');
const save = require('../lib/montage/save-timeline.ts');
(async () => {
  const rows = Array.from({ length: 2107 }, (_, i) => ({ id: String(i).padStart(5, '0'), video_time: i % 2 ? null : i }));
  let calls = 0;
  const loaded = await data.loadByIdCursor(async after => { calls++; return { data: rows.filter(r => !after || r.id > after).slice(0, 317), error: null }; });
  assert.deepEqual(loaded, rows); assert.equal(calls, 8);
  await assert.rejects(data.loadByIdCursor(async () => ({ data: null, error: { message: 'denied' } })), /denied/);
  await assert.rejects(data.loadByIdCursor(async () => ({ data: [{ id: 'same' }], error: null })), /progresse/);
  const action = { id:'a', quarter:2, video_time:100, clip_start:96, clip_end:104 };
  const match = state => ({ project_state: state });
  const bounds = state => data.synchronizeMontageAction(action, match(state));
  assert.equal(bounds({}).resolved_clip_start, 96);
  assert.equal(bounds({ videoSyncMode:'offset', videoSyncOffset:45 }).resolved_clip_start, 141);
  assert.equal(bounds({ videoSyncMode:'calibrated', videoSyncOffset:10, videoSyncRate:2 }).resolved_clip_end, 218);
  const edited = data.synchronizeMontageAction({ ...action, edited_clip_start:7, edited_clip_end:12 }, match({ videoSyncMode:'offset', videoSyncOffset:45 }));
  assert.equal(edited.resolved_clip_start, 7); assert.equal(edited.resolved_clip_end,12);
  const period = bounds({ periodMarkers: { '2': { start:200, sourceStart:90 } } });
  assert.equal(period.resolved_clip_start,206);
  assert.equal(data.hasMontageBounds(data.synchronizeMontageAction({ ...action, video_time:null, clip_start:null, clip_end:null })), false);
  assert.equal(action.clip_start,96); assert.equal(edited.clip_start,96);
  const clip = { item_type:'clip', clip_start:10, clip_end:16, sort_order:9, playbackRate:.5, repeatCount:2, timeline_start:80 };
  const input = [clip, { ...clip, item_type:'audio', duration:8, track:'audio', timeline_start:7 }, { ...clip, item_type:'freeze', playbackRate:1, repeatCount:1, freeze_duration:3 }, { ...clip, item_type:'text', duration:4, track:'overlay', timeline_start:5 }];
  const output = sequence.enforceTimelineSequence(input);
  assert.deepEqual(output.map(x => x.timeline_start), [0,7,24,5]);
  assert.deepEqual(output.map(x => x.sort_order), [0,1,2,3]);
  assert.equal(output[0].duration,24); assert.equal(output[2].duration,3); assert.equal(input[0].timeline_start,80);
  let rpcCalls=0;
  await assert.rejects(save.saveMontageAtomically({ rpc:async () => { rpcCalls++; return { error:{ code:'PGRST202', message:'missing' } }; } }, 'id', {}, [], null), /migration/);
  assert.equal(rpcCalls,1);
  const result = await save.saveMontageAtomically({ rpc:async (name,args) => { assert.equal(name,'save_montage_timeline_atomic'); assert.equal(args.p_expected_updated_at,'version'); return { data:{ id:'id', updated_at:'new' },error:null }; } }, 'id', {}, [], 'version');
  assert.equal(result.updated_at,'new');
  console.log('Montage: pagination, synchronisation, séquence et appel atomique validés.');
})().catch(error => { console.error(error); process.exitCode=1; }).finally(() => { require.extensions['.ts']=previous; });
